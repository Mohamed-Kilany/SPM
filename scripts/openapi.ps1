#Requires -Version 5.1
<#
.SYNOPSIS
Regenerates or verifies the OpenAPI contract from the Go route inventory.

.DESCRIPTION
The API contract in docs/openapi.yaml is generated by api/cmd/openapi from the
canonical route metadata in api/internal/server. Run without -Check to rewrite
the document after changing a route. Run with -Check to fail when the committed
document is out of date.

.PARAMETER Check
Verify the document is current without writing it.
#>
[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$apiRoot = Join-Path (Split-Path -Parent $PSScriptRoot) 'api'

Push-Location $apiRoot
try {
    if ($Check) {
        & go run ./cmd/openapi -check
    } else {
        & go run ./cmd/openapi -write
    }
    if ($LASTEXITCODE -ne 0) {
        throw "openapi exited with code $LASTEXITCODE"
    }
} finally {
    Pop-Location
}
